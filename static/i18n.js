  let locale = "zh-TW";

  function normalize(loc) {
    if (!loc) return "zh-TW";
    const s = String(loc);
    if (s === "en" || s.toLowerCase().startsWith("en")) return "en";
    return "zh-TW";
  }

  function t(key, vars) {
    const table = DICT[locale] || DICT["zh-TW"];
    let s = table[key] || (DICT["zh-TW"][key] || key);
    if (vars && typeof vars === "object") {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function applyI18n(root) {
    const scope = root || document;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      if (!key) return;
      const val = t(key);
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (!el.getAttribute("data-i18n-placeholder")) el.placeholder = val;
      } else {
        el.textContent = val;
      }
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.title = t(el.getAttribute("data-i18n-title"));
    });
    scope.querySelectorAll("[data-i18n-html]").forEach((el) => {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    document.documentElement.lang = locale === "en" ? "en" : "zh-Hant";
    document.querySelectorAll("[data-lang-btn]").forEach((btn) => {
      const L = btn.getAttribute("data-lang-btn");
      btn.classList.toggle("active", L === locale);
    });
  }

  function setLocale(loc, opts) {
    locale = normalize(loc);
    try {
      localStorage.setItem(STORAGE_KEY, locale);
    } catch (_) {}
    applyI18n(document);
    if (opts && typeof opts.onChange === "function") opts.onChange(locale);
    document.dispatchEvent(new CustomEvent("homelab:locale", { detail: { locale } }));
  }

  function getLocale() {
    return locale;
  }

  function initFromStorage() {
    let stored = null;
    try {
      stored = localStorage.getItem(STORAGE_KEY);
    } catch (_) {}
    locale = normalize(stored || locale);
    applyI18n(document);
  }

  global.HomelabI18n = {
    t,
    setLocale,
    getLocale,
    applyI18n,
    initFromStorage,
    STORAGE_KEY,
    DICT,
  };
  global.t = t;
